#!/usr/bin/env python3
"""Build data/phrases.js from data/phrases.json (the source of truth).

- Rows without an "id" get a stable id seed:<group>/<phrase> (with ~2, ~3 for extra senses).
  Existing ids are never changed: notes, images and review history are keyed by them.
- On first run, if data/phrases.json does not exist, rows are merged from data/parts/*.json.
- Also writes the legacy id map (v1 seed-<index> ids from the first MVP) into phrases.js.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'data'
GROUPS = ['IN', 'INTO', 'OUT', 'OUT OF', 'UP', 'DOWN', 'ON', 'OFF', 'OVER', 'AWAY', 'BACK',
          'ABOUT', '(A)ROUND', 'ACROSS', 'THROUGH', 'BY', 'ALONG']
BRANCHES = {'空間', '時間', '狀態', '程度', '完成', '情緒', '慣用'}

# First MVP (v1) stored seed ids by array index. Keep this order forever.
LEGACY_V1 = [
    ('UP', 'give up'), ('UP', 'use up'), ('UP', 'cheer up'), ('UP', 'set up'), ('UP', 'speed up'), ('UP', 'fill up'), ('UP', 'pick up'),
    ('OUT', 'find out'), ('OUT', 'point out'), ('OUT', 'run out of'), ('OUT', 'carry out'), ('OUT', 'leave out'),
    ('OFF', 'take off'), ('OFF', 'switch off'), ('OFF', 'cut off'), ('OFF', 'call off'), ('OFF', 'put off'),
    ('IN', 'join in'), ('IN', 'fill in'), ('IN', 'hand in'),
    ('INTO', 'turn into'), ('INTO', 'run into'),
    ('DOWN', 'slow down'), ('DOWN', 'calm down'), ('DOWN', 'break down'), ('DOWN', 'write down'),
    ('AWAY', 'go away'), ('AWAY', 'throw away'), ('AWAY', 'fade away'),
    ('ON', 'carry on'), ('ON', 'turn on'), ('ON', 'put on'), ('ON', 'go on'),
    ('OVER', 'get over'), ('OVER', 'think over'), ('OVER', 'look over'), ('OVER', 'take over'), ('OVER', 'go over'),
    ('BACK', 'come back'), ('BACK', 'give back'), ('BACK', 'call back'),
    ('ABOUT', 'move about'), ('(A)ROUND', 'turn around'), ('(A)ROUND', 'look around'),  # look around was in the ABOUT/(A)ROUND comparison tile
    ('ACROSS', 'come across'), ('ACROSS', 'get across'),
    ('THROUGH', 'go through'), ('THROUGH', 'get through'), ('THROUGH', 'think through'),
    ('BY', 'pass by'), ('ALONG', 'move along'),
]


def slug(s):
    return re.sub(r'^-+|-+$', '', re.sub(r'[^a-z0-9]+', '-', s.lower().replace('(', '').replace(')', '')))


def seed_id(group, phrase):
    return f'seed:{slug(group)}/{slug(phrase)}'


def main():
    src = DATA / 'phrases.json'
    if src.exists():
        rows = json.loads(src.read_text(encoding='utf-8'))
    else:
        rows = []
        for part in sorted((DATA / 'parts').glob('*.json')):
            rows += json.loads(part.read_text(encoding='utf-8'))
    errors = []
    ids = {r['id'] for r in rows if r.get('id')}
    for r in rows:
        if not r.get('id'):
            base = seed_id(r['group'], r['phrase'])
            rid, n = base, 2
            while rid in ids:
                rid, n = f'{base}~{n}', n + 1
            r['id'] = rid
            ids.add(rid)
    seen = set()
    for r in rows:
        if r['id'] in seen:
            errors.append(f'duplicate id {r["id"]}')
        seen.add(r['id'])
        if r.get('group') not in GROUPS:
            errors.append(f'{r["id"]}: unknown group {r.get("group")}')
        if r.get('branch') not in BRANCHES:
            errors.append(f'{r["id"]}: unknown branch {r.get("branch")}')
        for f in ('phrase', 'zh', 'hint', 'example'):
            if not str(r.get(f, '')).strip():
                errors.append(f'{r["id"]}: empty {f}')
        if not re.fullmatch(r'[a-z]+( [a-z]+)+', r.get('phrase', '')):
            errors.append(f'{r["id"]}: phrase format "{r.get("phrase")}"')
    legacy = {}
    for i, (g, p) in enumerate(LEGACY_V1):
        target = seed_id(g, p)
        if target not in seen:
            errors.append(f'legacy target missing: {target}')
        legacy[f'seed-{i}'] = target
    if errors:
        print('\n'.join(errors), file=sys.stderr)
        sys.exit(1)
    keys = ['id', 'group', 'phrase', 'zh', 'hint', 'example', 'branch', 'separable']
    rows = [{k: r.get(k) for k in keys} for r in rows]
    src.write_text(json.dumps(rows, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    js = ('// Generated by scripts/build_data.py from data/phrases.json — do not edit by hand.\n'
          '// Seed ids are permanent; never renumber them.\n'
          'window.PHRASEMAP_SEED=' + json.dumps(rows, ensure_ascii=False) + ';\n'
          'window.PHRASEMAP_LEGACY_IDS=' + json.dumps(legacy) + ';\n')
    (DATA / 'phrases.js').write_text(js, encoding='utf-8')
    counts = {g: sum(1 for r in rows if r['group'] == g) for g in GROUPS}
    print(f'{len(rows)} phrase senses;', ', '.join(f'{g} {c}' for g, c in counts.items()))


if __name__ == '__main__':
    main()
